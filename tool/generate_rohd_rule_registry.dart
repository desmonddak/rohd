import 'dart:io';

import 'package:yaml/yaml.dart';

void main() {
  final root = Directory.current;
  final registry = loadYaml(
    File('${root.path}/analyzer/rules/rohd_rules.yaml').readAsStringSync(),
  ) as YamlMap;
  final rules = (registry['rules'] as YamlList).cast<YamlMap>();

  Directory('${root.path}/packages/rohd_analyzer_plugin/lib/src/generated')
      .createSync(recursive: true);
  File(
    '${root.path}/packages/rohd_analyzer_plugin/lib/src/generated/'
    'rohd_rule_registry.dart',
  ).writeAsStringSync(_dart(rules));
}

List<String> _strings(Object? value) => value is Iterable
    ? value.map((item) => item.toString()).toList()
    : const [];

String _constantPrefix(YamlMap rule) {
  final words = rule['slug'].toString().split('_');
  return words.first +
      words
          .skip(1)
          .map((word) => '${word[0].toUpperCase()}${word.substring(1)}')
          .join();
}

String _dart(List<YamlMap> rules) {
  final constants = rules.map((rule) {
    final prefix = _constantPrefix(rule);
    final analyzerDeclaration =
        "const ${prefix}AnalyzerName = '${rule['analyzerName']}';";
    final formattedAnalyzerDeclaration = analyzerDeclaration.length <= 80
        ? analyzerDeclaration
        : 'const ${prefix}AnalyzerName =\n'
            "    '${rule['analyzerName']}';";
    return '''
/// Stable identifier for `${rule['slug']}`.
const ${prefix}RuleId = '${rule['id']}';

/// Dart analyzer name for `${rule['slug']}`.
$formattedAnalyzerDeclaration''';
  }).join('\n\n');
  final hardwareRoots = _strings(
    rules.expand((rule) => _strings(rule['hardwareTypeRoots'])).toList(),
  );
  final legalExposureMethods = _strings(
    rules.expand((rule) => _strings(rule['legalExposureMethods'])).toList(),
  );
  final mutationMethods = _strings(
    rules.expand((rule) => _strings(rule['mutationMethods'])).toList(),
  );
  final hardwareRootSet = _dartStringSet(
    'rohdHardwareTypeRoots',
    hardwareRoots,
  );
  final legalExposureSet = _dartStringSet(
    'rohdLegalExposureMethods',
    legalExposureMethods,
  );
  final mutationMethodSet = _dartStringSet(
    'rohdConstMutationMethods',
    mutationMethods,
  );
  return '''
// GENERATED CODE - DO NOT EDIT.
// Generated by tool/generate_rohd_rule_registry.dart.

$constants

/// Resolved hardware type roots used by the semantic adapter.
$hardwareRootSet

/// Methods that expose a signal through a current module-owned port.
$legalExposureSet

/// ROHD `Logic` mutation methods that cannot be called on a `Const`.
$mutationMethodSet
''';
}

String _dartStringSet(String name, List<String> values) {
  final inlineValues = values.map((value) => "'$value'").join(', ');
  final inline = 'const $name = <String>{$inlineValues};';
  if (inline.length <= 80) {
    return inline;
  }
  return '''
const $name = <String>{
${values.map((value) => "  '$value',").join('\n')}
};''';
}
